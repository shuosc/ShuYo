/// Strict GBK/Windows-936 decoding for the public VSB metadata export.
///
/// ASCII is copied directly and the Windows-936 single byte 0x80 means euro.
/// Invalid, unmapped or incomplete sequences throw so callers can retain their
/// original HTML metadata rather than display replacement characters.
String decodeAnnouncementGbk(List<int> bytes) {
  final decoded = StringBuffer();
  for (var index = 0; index < bytes.length; index++) {
    final lead = bytes[index];
    if (lead >= 0 && lead < 0x80) {
      decoded.writeCharCode(lead);
      continue;
    }
    if (lead == 0x80) {
      decoded.writeCharCode(0x20ac);
      continue;
    }
    if (lead < 0x81 || lead > 0xfe || index + 1 >= bytes.length) {
      throw FormatException(
          'Invalid or incomplete GBK leading byte', null, index);
    }
    final trail = bytes[++index];
    if (trail < 0x40 || trail > 0xfe || trail == 0x7f) {
      throw FormatException('Invalid GBK trailing byte', null, index);
    }
    final slot = (lead - 0x81) * 190 + trail - 0x40 - (trail > 0x7f ? 1 : 0);
    final rune = _gbkRune(slot);
    if (rune == 0) {
      throw FormatException('Unmapped GBK byte sequence', null, index - 1);
    }
    decoded.writeCharCode(rune);
  }
  return decoded.toString();
}

/// Whether the export's GBK encoding can represent this Unicode scalar.
bool isAnnouncementGbkCharacter(int rune) =>
    (rune >= 0 && rune < 0x80) ||
    rune == 0x20ac ||
    _gbkCharacters.contains(rune);

int _gbkRune(int slot) {
  final offset = slot * 2;
  return (_gbkMapping[offset] << 8) | _gbkMapping[offset + 1];
}

